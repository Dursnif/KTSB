"""DT04-S05j — setup never makes the user's docker-compose.override.yml disappear without a word.

README («Updating») tells the user to put their own compose changes in docker-compose.override.yml. setup.sh /
setup.ps1 also write that file for GPU passthrough, and used to overwrite it (GPU) or delete it (no GPU) without
looking at it. Now:
- no file → setup writes its own (first line «# Auto-generated by setup…» = the marker);
- marker + unchanged → setup may replace or remove it, as before;
- marker + edited → setup copies it to docker-compose.override.yml.bak-<time> first and says so;
- no marker → the user's file: never touched; setup prints the GPU block to add by hand.
The updater (P57) never touches the file — tests/test_p57_updater.py::test_previous_roundtrip_leaves_user_files_alone.
"""

import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path("/kaare")
MINE = "services:\n  kaare:\n    ports:\n      - \"9999:9999\"   # my own change\n"


def _run_block(tmp_path, call: str) -> str:
    """Source the override-helpers block of setup.sh and run `call` in tmp_path."""
    script = (
        "set -euo pipefail; "
        f'source <(sed -n "/^# >>> override-helpers/,/^# <<< override-helpers/p" {ROOT}/setup.sh); '
        f"cd {tmp_path}; {call}"
    )
    r = subprocess.run(["bash", "-c", script], capture_output=True, text=True, timeout=30)
    assert r.returncode == 0, r.stderr
    return r.stdout


def _baks(tmp_path):
    return sorted(tmp_path.glob("docker-compose.override.yml.bak-*"))


# ── the whole script, as a user runs it ─────────────────────────────────────────

def test_setup_sh_keeps_the_users_own_override_byte_for_byte(tmp_path):
    for f in ("setup.sh", ".env.example"):
        shutil.copy(ROOT / f, tmp_path / f)
    own = tmp_path / "docker-compose.override.yml"
    own.write_text(MINE)
    r = subprocess.run(["bash", str(tmp_path / "setup.sh")], input="y\n", capture_output=True, text=True,
                       timeout=120, cwd=tmp_path)
    assert r.returncode == 0, r.stderr
    assert own.read_text() == MINE  # whatever GPU this machine has
    assert "your own" in r.stdout
    assert not _baks(tmp_path)


# ── the block, per case ─────────────────────────────────────────────────────────

def test_no_file_gpu_writes_ktsbs_file_with_the_marker(tmp_path):
    out = _run_block(tmp_path, 'apply_override docker-compose.override.yml "$OVERRIDE_NVIDIA" "the NVIDIA GPU"')
    text = (tmp_path / "docker-compose.override.yml").read_text()
    assert text.startswith("# Auto-generated by setup")
    assert "driver: nvidia" in text and "remove the first line" in text.lower()
    assert "written" in out


def test_no_file_cpu_writes_nothing(tmp_path):
    _run_block(tmp_path, 'apply_override docker-compose.override.yml "" ""')
    assert not (tmp_path / "docker-compose.override.yml").exists()


def test_ktsbs_unchanged_file_is_removed_in_cpu_mode_without_a_copy(tmp_path):
    _run_block(tmp_path, 'apply_override docker-compose.override.yml "$OVERRIDE_NVIDIA" "x"')
    out = _run_block(tmp_path, 'apply_override docker-compose.override.yml "" ""')
    assert not (tmp_path / "docker-compose.override.yml").exists()
    assert not _baks(tmp_path) and "removed" in out


def test_legacy_file_from_an_older_setup_counts_as_unchanged(tmp_path):
    # What setup.sh wrote up to v1.10 (no ownership line yet).
    legacy = (
        "# Auto-generated by setup.sh — NVIDIA GPU detected.\n# Adds GPU passthrough to Ollama.\n"
        "# Requirements: nvidia-container-toolkit must be installed on the host.\nservices:\n  ollama:\n"
        "    deploy:\n      resources:\n        reservations:\n          devices:\n            - driver: nvidia\n"
        "              count: all\n              capabilities: [gpu]\n"
    )
    (tmp_path / "docker-compose.override.yml").write_text(legacy)
    _run_block(tmp_path, 'apply_override docker-compose.override.yml "" ""')
    assert not (tmp_path / "docker-compose.override.yml").exists() and not _baks(tmp_path)


def test_ktsbs_file_edited_by_the_user_is_copied_aside_first(tmp_path):
    _run_block(tmp_path, 'apply_override docker-compose.override.yml "$OVERRIDE_NVIDIA" "x"')
    f = tmp_path / "docker-compose.override.yml"
    edited = f.read_text() + "  kaare:\n    ports:\n      - \"9999:9999\"\n"
    f.write_text(edited)
    out = _run_block(tmp_path, 'apply_override docker-compose.override.yml "$OVERRIDE_INTEL" "the Intel GPU"')
    baks = _baks(tmp_path)
    assert len(baks) == 1 and baks[0].read_text() == edited
    assert "OLLAMA_INTEL_GPU" in f.read_text()
    assert baks[0].name in out


def test_users_own_file_is_never_touched_and_the_gpu_block_is_shown(tmp_path):
    f = tmp_path / "docker-compose.override.yml"
    f.write_text(MINE)
    out = _run_block(tmp_path, 'apply_override docker-compose.override.yml "$OVERRIDE_NVIDIA" "the NVIDIA GPU"')
    assert f.read_text() == MINE and not _baks(tmp_path)
    assert "driver: nvidia" in out  # what to add by hand
    out = _run_block(tmp_path, 'apply_override docker-compose.override.yml "" ""')
    assert f.read_text() == MINE and not _baks(tmp_path)


def test_marker_after_a_bom_or_crlf_still_counts(tmp_path):
    _run_block(tmp_path, 'apply_override docker-compose.override.yml "$OVERRIDE_NVIDIA" "x"')
    f = tmp_path / "docker-compose.override.yml"
    f.write_bytes(b"\xef\xbb\xbf" + f.read_text().replace("\n", "\r\n").encode())
    _run_block(tmp_path, 'apply_override docker-compose.override.yml "" ""')
    assert not f.exists() and not _baks(tmp_path)


# ── setup.ps1 (no PowerShell on the test machine: the same rule, read as text) ──

def test_setup_ps1_has_the_same_rule():
    ps1 = (ROOT / "setup.ps1").read_text(encoding="utf-8")
    # Every Remove-Item / Set-Content on the override goes through the one guarded function.
    assert len(re.findall(r"Remove-Item\s+\$(OverrideFile|File)\b", ps1)) == 1
    assert len(re.findall(r"Set-Content\s+-Path\s+\$(OverrideFile|File)\b", ps1)) == 1
    fn = ps1[ps1.index("# >>> override-helpers"):ps1.index("# <<< override-helpers")]
    assert "# Auto-generated by setup" in fn and ".bak-" in fn and "your own" in fn
    assert "remove the first line" in ps1.lower()


def test_readme_says_how_the_file_is_kept():
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    assert "Auto-generated by setup" in readme and ".bak-" in readme
