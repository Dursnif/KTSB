"""Service token — how KTSB's own services prove they are KTSB (P120 Phase 2).

The token is a random secret in configs/service_token.env (KAARE_SERVICE_TOKEN), generated by
the API at its first start (a bootstrap value, rule 25's exception: it must exist before the
GUI can run, and no user ever sees or edits it). Services on the same install read the same
file and send it in the X-Kaare-Service-Token header. Only a request carrying it may say which
user it acts for (voice → the identified speaker, timers → the timer's owner) or claim an
internal source; everything else must log in with a user token.

Standard library only: the voice bridge (its own venv) imports this module.
"""

import hmac
import logging
import os
import secrets
from pathlib import Path

from kaare_core import config_store

logger = logging.getLogger(__name__)

SERVICE_HEADER = "X-Kaare-Service-Token"
_TOKEN_PATH = Path("/kaare/configs/service_token.env")
_KEY = "KAARE_SERVICE_TOKEN"
_cache: dict = {"mtime": None, "token": ""}


def ensure_service_token() -> None:
    """Create the token file if it is missing. Never overwrites an existing token."""
    try:
        if _TOKEN_PATH.exists() and _read_file():
            return
        with config_store.lock(
            _TOKEN_PATH
        ):  # two processes starting at once must agree on one token
            if _TOKEN_PATH.exists() and _read_file():
                return
            config_store.write_text(
                _TOKEN_PATH,
                "# Generated by KTSB at first start — shared secret between KTSB's own services.\n"
                "# Do not share. Delete this file and restart all KTSB services to rotate it.\n"
                f"{_KEY}={secrets.token_urlsafe(32)}\n",
                "service-token-created",
                mode=0o640,
            )
        os.chmod(_TOKEN_PATH, 0o640)
        logger.info("[SERVICE_AUTH] service token created at %s", _TOKEN_PATH)
    except Exception as e:
        logger.error("[SERVICE_AUTH] could not create the service token: %s", e)


def _read_file() -> str:
    for line in _TOKEN_PATH.read_text(encoding="utf-8").splitlines():
        key, _, value = line.strip().partition("=")
        if key == _KEY and value:
            return value.strip()
    return ""


def get_service_token() -> str:
    """The token, re-read only when the file changes. Empty string when unavailable."""
    try:
        mtime = _TOKEN_PATH.stat().st_mtime
        if mtime != _cache["mtime"]:
            _cache.update(mtime=mtime, token=_read_file())
        return _cache["token"]
    except Exception:
        return ""


def service_headers() -> dict:
    """Headers a KTSB service adds to its own calls to the API."""
    token = get_service_token()
    return {SERVICE_HEADER: token} if token else {}


def is_service_request(headers) -> bool:
    """True when the request carries the valid service token (constant-time compare).
    Fails closed: no token configured → no request is a service request."""
    expected = get_service_token()
    given = headers.get(SERVICE_HEADER) or ""
    return bool(expected) and hmac.compare_digest(given.encode(), expected.encode())
